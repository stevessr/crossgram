export type Language = 'en-US' | 'zh-CN'
export const languageStorageKey = 'crossgram:webui-language'

function initialLanguage(): Language {
  try {
    const saved = localStorage.getItem(languageStorageKey)
    if (saved === 'en-US' || saved === 'zh-CN') return saved
  } catch {
    // Web storage can be unavailable (for example, private browsing).
  }
  return typeof navigator !== 'undefined' &&
    (/^zh(?:-|$)/i.test(navigator.languages?.[0] ?? navigator.language))
    ? 'zh-CN'
    : 'en-US'
}

const [current, setCurrent] = createSignal<Language>(initialLanguage())
export const language = current

/** The language is per-browser and never written to the relay's server config. */
export function setLanguage(next: Language): void {
  if (next !== 'en-US' && next !== 'zh-CN') return
  setCurrent(next)
  if (typeof document !== 'undefined') document.documentElement.lang = next
  try {
    localStorage.setItem(languageStorageKey, next)
  } catch {
    // Keep in-memory selection even when storage is disabled.
  }
}

/** The original English string is the fallback for missing translations. */
export function t(source: string): string {
  return current() === 'zh-CN' ? (zhCN[source] ?? source) : source
}
